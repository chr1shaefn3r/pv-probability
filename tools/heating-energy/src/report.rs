//! The degree day report: what the weather asked of the heating, month by month, and how
//! warm every room was kept meanwhile, as one self-contained HTML file.

use std::fmt::Write as _;

use chrono_tz::Tz;

use ha_recorder::coverage::Coverage;
use ha_recorder::model::Grouping;
use ha_report::axis::nice_ticks;
use ha_report::layout::{
    CHROME_CSS, Shell, coverage_section, document, metadata_list, theme_stylesheet,
};
use ha_report::{escape, format_percent};

use crate::degree::{Analysis, Summary};
use crate::rooms::House;

/// Everything the page needs beyond the analysis itself.
#[derive(Debug, Clone, PartialEq)]
pub struct ReportOptions {
    pub outside_entity: String,
    pub house: Option<House>,
    /// Facts about the run: source table, timezone, date range.
    pub metadata: Vec<(String, String)>,
    pub coverage: Option<Coverage>,
    pub tz: Tz,
}

impl Default for ReportOptions {
    fn default() -> Self {
        Self {
            outside_entity: String::new(),
            house: None,
            metadata: Vec::new(),
            coverage: None,
            tz: Tz::UTC,
        }
    }
}

/// Render the complete HTML document.
pub fn page(analysis: &Analysis, options: &ReportOptions) -> String {
    let title = "Heating and cooling degree days".to_string();
    let mut body = String::with_capacity(32 * 1024);

    body.push_str(&metadata_list(&metadata_entries(analysis, options)));
    body.push_str(&degree_day_section(analysis, options));
    if let Some(house) = &options.house {
        body.push_str(&rooms_section(analysis, house));
    }
    body.push_str(&years_section(analysis, options));
    body.push_str(&method_section(analysis));
    if let Some(coverage) = &options.coverage {
        body.push_str(&coverage_section(
            coverage,
            options.tz,
            Grouping::Month,
            None,
        ));
    }

    document(
        &Shell {
            title: &title,
            lede: &lede(analysis),
            stylesheet: &stylesheet(),
            defs: "",
            footer: "Degree days measure the weather, not the house: a month with twice the \
                     heating degree days asked for about twice the heat to keep it at the same \
                     temperature. Generated by heating-energy from a Home Assistant recorder \
                     database.",
        },
        &body,
    )
}

fn lede(analysis: &Analysis) -> String {
    format!(
        "How much heating - and cooling - the weather asked for, {}. A day averaging below \
         {} outside counts one heating degree day for every degree below it; a day averaging \
         above {}, one cooling degree day for every degree above.",
        match analysis.grouping {
            Grouping::Month => "month by month",
            Grouping::Week => "week by week",
        },
        format_celsius(analysis.bases.heating),
        format_celsius(analysis.bases.cooling)
    )
}

fn metadata_entries(analysis: &Analysis, options: &ReportOptions) -> Vec<(String, String)> {
    let mut entries = vec![
        ("Outside".to_string(), options.outside_entity.clone()),
        (
            "Heating base".to_string(),
            format_celsius(analysis.bases.heating),
        ),
        (
            "Cooling base".to_string(),
            format_celsius(analysis.bases.cooling),
        ),
    ];
    entries.extend(options.metadata.iter().cloned());
    entries.push((
        "Days counted".to_string(),
        format!(
            "{} of {}",
            analysis.record.days, analysis.record.possible_days
        ),
    ));
    if let Some(house) = &options.house {
        entries.push((
            "Rooms".to_string(),
            format!(
                "{} on {} floor{}",
                house.room_count(),
                house.floors.len(),
                if house.floors.len() == 1 { "" } else { "s" }
            ),
        ));
    }
    entries
}

/// The chart and its table twin: degree days per period, with the outside and the floors.
fn degree_day_section(analysis: &Analysis, options: &ReportOptions) -> String {
    let unit = match analysis.grouping {
        Grouping::Month => "month",
        Grouping::Week => "week",
    };
    let mut html = format!("<section class=\"panel degree-days\"><h2>Degree days per {unit}</h2>");
    if analysis.periods.is_empty() {
        let _ = write!(
            html,
            "<p class=\"empty\">No day was recorded fully enough to count: the outside \
             thermometer has to cover {} of a day.</p></section>",
            format_percent(analysis.min_coverage)
        );
        return html;
    }
    html.push_str(&legend(analysis));
    html.push_str(&chart(analysis));
    html.push_str(&period_table(analysis, options.house.as_ref()));
    html.push_str("</section>");
    html
}

fn legend(analysis: &Analysis) -> String {
    let cooling = if analysis.record.cdd > 0.0 {
        "below the line".to_string()
    } else {
        "none in this record".to_string()
    };
    format!(
        "<ul class=\"key\"><li><span class=\"swatch hdd\" aria-hidden=\"true\"></span>Heating \
         degree days, above the line</li><li><span class=\"swatch cdd\" aria-hidden=\"true\">\
         </span>Cooling degree days, {cooling}</li></ul>"
    )
}

// Chart geometry, in user units. The viewBox scales to whatever width the panel has.
const PLOT_WIDTH: f64 = 880.0;
const MARGIN_LEFT: f64 = 52.0;
const MARGIN_RIGHT: f64 = 12.0;
/// Room above the plot for the hover readout, so no bar can cover it.
const MARGIN_TOP: f64 = 30.0;
const READOUT_BASELINE: f64 = 14.0;
const _: () = assert!(READOUT_BASELINE < MARGIN_TOP - 10.0);
const PLOT_HEIGHT: f64 = 220.0;
const MARGIN_BOTTOM: f64 = 40.0;
/// The widest a bar gets, however few periods there are.
const MAX_BAR: f64 = 24.0;
/// The rounding at a bar's data end.
const RADIUS: f64 = 4.0;
/// Room beyond the longest bar of each arm for its direct label.
const LABEL_ROOM: f64 = 14.0;

/// Heating degree days rise above one baseline and cooling degree days hang below it, on
/// the same scale: both are degree days, so one axis serves both arms.
fn chart(analysis: &Analysis) -> String {
    let periods = &analysis.periods;
    let max_hdd = periods.iter().map(|period| period.hdd).fold(0.0, f64::max);
    let max_cdd = periods.iter().map(|period| period.cdd).fold(0.0, f64::max);
    // One tick step for both arms, from whichever reaches further.
    let step = nice_ticks(max_hdd.max(max_cdd), 4)
        .get(1)
        .copied()
        .unwrap_or(1.0);
    let span = (max_hdd + max_cdd).max(f64::MIN_POSITIVE);
    let below = if max_cdd > 0.0 { LABEL_ROOM } else { 0.0 };
    let scale = (PLOT_HEIGHT - LABEL_ROOM - below) / span;
    let baseline = MARGIN_TOP + LABEL_ROOM + max_hdd * scale;
    let width = MARGIN_LEFT + PLOT_WIDTH + MARGIN_RIGHT;
    let height = MARGIN_TOP + PLOT_HEIGHT + MARGIN_BOTTOM;
    let slot = PLOT_WIDTH / periods.len() as f64;
    let bar = (slot * 0.7).min(MAX_BAR);

    let mut svg = String::with_capacity(16 * 1024);
    let _ = write!(
        svg,
        "<svg class=\"degree-chart\" viewBox=\"0 0 {width:.0} {height:.0}\" role=\"img\" \
         aria-label=\"Heating and cooling degree days per period\" \
         preserveAspectRatio=\"xMidYMid meet\">"
    );

    // Gridlines either side of the baseline, labelled with the distance from it: a cooling
    // degree day below the line is as positive as a heating one above.
    svg.push_str("<g class=\"grid\">");
    for (extent, direction) in [(max_hdd, -1.0), (max_cdd, 1.0)] {
        let mut tick = step;
        while tick <= extent + step * 1e-9 {
            let y = baseline + direction * tick * scale;
            let _ = write!(
                svg,
                "<line x1=\"{MARGIN_LEFT:.1}\" y1=\"{y:.1}\" x2=\"{:.1}\" y2=\"{y:.1}\"/>\
                 <text class=\"tick\" x=\"{:.1}\" y=\"{:.1}\" text-anchor=\"end\">{}</text>",
                MARGIN_LEFT + PLOT_WIDTH,
                MARGIN_LEFT - 6.0,
                y + 4.0,
                escape(&format_degree_days(tick))
            );
            tick += step;
        }
    }
    let _ = write!(
        svg,
        "<text class=\"axis-title\" x=\"{MARGIN_LEFT:.1}\" y=\"{:.1}\">heating degree days</text>",
        MARGIN_TOP - 4.0
    );
    if max_cdd > 0.0 {
        let _ = write!(
            svg,
            "<text class=\"axis-title\" x=\"{MARGIN_LEFT:.1}\" y=\"{:.1}\">cooling degree \
             days</text>",
            MARGIN_TOP + PLOT_HEIGHT + 14.0
        );
    }
    svg.push_str("</g>");

    // One group per period: a hit area the full height of the plot, its bars, and the
    // readout hovering it reveals.
    let hottest = index_of_max(periods, |period| period.cdd);
    let coldest = index_of_max(periods, |period| period.hdd);
    svg.push_str("<g class=\"series\">");
    for (index, period) in periods.iter().enumerate() {
        let left = MARGIN_LEFT + index as f64 * slot;
        let x = left + (slot - bar) / 2.0;
        let mut marks = format!(
            "<rect class=\"hit\" x=\"{left:.1}\" y=\"{MARGIN_TOP:.1}\" width=\"{slot:.1}\" \
             height=\"{PLOT_HEIGHT:.1}\"/>"
        );
        if period.hdd > 0.0 {
            let end = baseline - period.hdd * scale;
            let _ = write!(
                marks,
                "<path class=\"hdd\" d=\"{}\"/>",
                column(x, bar, baseline, end)
            );
        }
        if period.cdd > 0.0 {
            let end = baseline + period.cdd * scale;
            let _ = write!(
                marks,
                "<path class=\"cdd\" d=\"{}\"/>",
                column(x, bar, baseline, end)
            );
        }
        // Direct labels only on the extremes; the axis and the readout carry the rest.
        if Some(index) == coldest {
            let _ = write!(
                marks,
                "<text class=\"value\" x=\"{:.1}\" y=\"{:.1}\" text-anchor=\"middle\">{}</text>",
                x + bar / 2.0,
                baseline - period.hdd * scale - 4.0,
                escape(&format_degree_days(period.hdd))
            );
        }
        if Some(index) == hottest {
            let _ = write!(
                marks,
                "<text class=\"value\" x=\"{:.1}\" y=\"{:.1}\" text-anchor=\"middle\">{}</text>",
                x + bar / 2.0,
                baseline + period.cdd * scale + 12.0,
                escape(&format_degree_days(period.cdd))
            );
        }
        let _ = write!(
            svg,
            "<g class=\"slot\">{marks}<text class=\"readout\" x=\"{MARGIN_LEFT:.1}\" \
             y=\"{READOUT_BASELINE:.1}\">{}</text></g>",
            escape(&describe(period))
        );
    }
    svg.push_str("</g>");

    // The baseline over the bars, and the period labels under the plot.
    let _ = write!(
        svg,
        "<g class=\"axis\"><line x1=\"{MARGIN_LEFT:.1}\" y1=\"{baseline:.1}\" x2=\"{:.1}\" \
         y2=\"{baseline:.1}\"/>",
        MARGIN_LEFT + PLOT_WIDTH
    );
    let label_y = MARGIN_TOP + PLOT_HEIGHT + if max_cdd > 0.0 { 28.0 } else { 16.0 };
    let every = label_stride(slot);
    let mut last_year = None;
    for (index, period) in periods.iter().enumerate() {
        let centre = MARGIN_LEFT + (index as f64 + 0.5) * slot;
        let year = period.period.year();
        // A new year always gets its label, so the reader never loses track of which
        // January is which.
        let new_year = year != last_year;
        last_year = year;
        if index % every == 0 || new_year {
            let label = if new_year {
                format!(
                    "{} {}",
                    period.period.short_label(),
                    year.map(|year| format!("{:02}", year.rem_euclid(100)))
                        .unwrap_or_default()
                )
            } else {
                period.period.short_label()
            };
            let _ = write!(
                svg,
                "<text class=\"tick{}\" x=\"{centre:.1}\" y=\"{label_y:.1}\" \
                 text-anchor=\"middle\">{}</text>",
                if new_year { " year" } else { "" },
                escape(&label)
            );
        }
    }
    svg.push_str("</g></svg>");
    svg
}

/// A column from `base` to `end`, rounded at the data end and square at the baseline,
/// whichever way it points.
fn column(x: f64, width: f64, base: f64, end: f64) -> String {
    let length = (end - base).abs();
    let radius = RADIUS.min(width / 2.0).min(length);
    let toward = if end < base { 1.0 } else { -1.0 };
    let shoulder = end + toward * radius;
    let sweep = if end < base { 1 } else { 0 };
    format!(
        "M{x:.1},{base:.1}V{shoulder:.1}A{radius:.1},{radius:.1} 0 0 {sweep} {:.1},{end:.1}\
         H{:.1}A{radius:.1},{radius:.1} 0 0 {sweep} {:.1},{shoulder:.1}V{base:.1}Z",
        x + radius,
        x + width - radius,
        x + width
    )
}

/// How many slots apart the period labels sit, so they do not run into each other.
fn label_stride(slot: f64) -> usize {
    const LABEL_WIDTH: f64 = 34.0;
    ((LABEL_WIDTH / slot).ceil() as usize).max(1)
}

fn index_of_max(periods: &[Summary], value: impl Fn(&Summary) -> f64) -> Option<usize> {
    periods
        .iter()
        .enumerate()
        .filter(|(_, period)| value(period) > 0.0)
        .max_by(|(_, left), (_, right)| value(left).total_cmp(&value(right)))
        .map(|(index, _)| index)
}

/// The hover line for one period.
fn describe(period: &Summary) -> String {
    let mut text = format!(
        "{}: {} heating, {} cooling degree days",
        period.period.label(),
        format_degree_days(period.hdd),
        format_degree_days(period.cdd)
    );
    if let Some(outside) = period.outside {
        let _ = write!(text, ", {} outside on average", format_celsius(outside));
    }
    let _ = write!(text, " - {}", days(period));
    text
}

fn days(period: &Summary) -> String {
    if period.is_complete() {
        format!("{} days", period.days)
    } else {
        format!("{} of {} days", period.days, period.possible_days)
    }
}

/// The table twin of the chart: every period, with the floors' indoor means beside it.
fn period_table(analysis: &Analysis, house: Option<&House>) -> String {
    let mut html = String::from(
        "<div class=\"table-scroll\"><table><caption>Per period. A period missing days counts \
         only the days recorded, so its degree days are a floor rather than the total; the \
         Days column says how many counted.</caption><thead><tr><th scope=\"col\">Period</th>\
         <th scope=\"col\">Days</th><th scope=\"col\">Outside</th><th scope=\"col\">Heating \
         degree days</th><th scope=\"col\">Cooling degree days</th>",
    );
    if let Some(house) = house {
        for floor in &house.floors {
            let _ = write!(html, "<th scope=\"col\">{}</th>", escape(&floor.name));
        }
    }
    html.push_str("</tr></thead><tbody>");
    for period in &analysis.periods {
        html.push_str(&summary_row(period, house.is_some()));
    }
    html.push_str("</tbody><tfoot>");
    html.push_str(&summary_row(&analysis.record, house.is_some()));
    html.push_str("</tfoot></table></div>");
    html
}

fn summary_row(summary: &Summary, with_floors: bool) -> String {
    let mut html = format!(
        "<tr><th scope=\"row\">{}</th><td class=\"{}\">{}</td><td>{}</td><td>{}</td><td>{}</td>",
        escape(&summary.period.label()),
        if summary.is_complete() {
            "days"
        } else {
            "days partial"
        },
        escape(&days(summary)),
        escape(&table_celsius(summary.outside)),
        escape(&table_degree_days(summary.hdd)),
        escape(&table_degree_days(summary.cdd))
    );
    if with_floors {
        for floor in &summary.floors {
            let _ = write!(html, "<td>{}</td>", escape(&table_celsius(*floor)));
        }
    }
    html.push_str("</tr>");
    html
}

/// Every room, a floor at a time, over the same days the degree days were counted on.
fn rooms_section(analysis: &Analysis, house: &House) -> String {
    let mut html = String::from(
        "<section class=\"panel rooms\"><h2>Indoor temperatures</h2><p>Each room's mean over \
         the days the degree days were counted on, wherever its own thermometer covered the day \
         as well. A floor's figure is the plain mean of its rooms, every room counting alike.\
         </p>",
    );
    let mut first = 0;
    for (index, floor) in house.floors.iter().enumerate() {
        let rooms = first..first + floor.rooms.len();
        first = rooms.end;
        let _ = write!(
            html,
            "<details class=\"floor\"><summary>{}: {} on average, over {} room{}</summary>\
             <div class=\"table-scroll\"><table><caption>{} by {}</caption><thead><tr>\
             <th scope=\"col\">Period</th>",
            escape(&floor.name),
            escape(&format_optional_celsius(
                analysis.record.floors.get(index).copied().flatten()
            )),
            floor.rooms.len(),
            if floor.rooms.len() == 1 { "" } else { "s" },
            escape(&floor.name),
            match analysis.grouping {
                Grouping::Month => "month",
                Grouping::Week => "week",
            }
        );
        for room in &floor.rooms {
            let _ = write!(html, "<th scope=\"col\">{}</th>", escape(&room.name));
        }
        html.push_str("</tr></thead><tbody>");
        for summary in &analysis.periods {
            html.push_str(&room_row(summary, rooms.clone()));
        }
        html.push_str("</tbody><tfoot>");
        html.push_str(&room_row(&analysis.record, rooms));
        html.push_str("</tfoot></table></div></details>");
    }
    html.push_str("</section>");
    html
}

fn room_row(summary: &Summary, rooms: std::ops::Range<usize>) -> String {
    let mut html = format!(
        "<tr><th scope=\"row\">{}</th>",
        escape(&summary.period.label())
    );
    for room in rooms {
        let value = summary.rooms.get(room).copied().flatten();
        let _ = write!(html, "<td>{}</td>", escape(&table_celsius(value)));
    }
    html.push_str("</tr>");
    html
}

/// Calendar years side by side: the figure a heating season is usually compared by.
fn years_section(analysis: &Analysis, options: &ReportOptions) -> String {
    if analysis.years.is_empty() {
        return String::new();
    }
    let mut html = String::from(
        "<section class=\"panel years\"><h2>Per year</h2><div class=\"table-scroll\"><table>\
         <caption>Calendar years. A year the record only partly covers is a floor, not a total.\
         </caption><thead><tr><th scope=\"col\">Year</th><th scope=\"col\">Days</th>\
         <th scope=\"col\">Outside</th><th scope=\"col\">Heating degree days</th>\
         <th scope=\"col\">Cooling degree days</th>",
    );
    if let Some(house) = &options.house {
        for floor in &house.floors {
            let _ = write!(html, "<th scope=\"col\">{}</th>", escape(&floor.name));
        }
    }
    html.push_str("</tr></thead><tbody>");
    for year in &analysis.years {
        html.push_str(&summary_row(year, options.house.is_some()));
    }
    html.push_str("</tbody></table></div></section>");
    html
}

/// How the figures were arrived at, in the reader's terms.
fn method_section(analysis: &Analysis) -> String {
    let heating = format_celsius(analysis.bases.heating);
    let cooling = format_celsius(analysis.bases.cooling);
    let mut html = format!(
        "<section class=\"panel method\"><h2>How it is counted</h2><p>Each day's mean outside \
         temperature is the average of everything the thermometer recorded that day, every \
         reading weighted by how long it held. A day averaging 3 °C counts \
         <strong>{}</strong> heating degree days against the {heating} base; a day averaging \
         above {heating} counts none. Cooling degree days count the other way, from {cooling}.\
         </p><p>A day counts only when the outside thermometer covered at least {} of it: a day \
         whose night is missing reads warm and would understate the heating it needed.",
        escape(&format_degree_days(analysis.bases.hdd(3.0))),
        escape(&format_percent(analysis.min_coverage))
    );
    if analysis.short_days > 0 {
        let _ = write!(
            html,
            " {} day{} fell short of that and {} left out.",
            analysis.short_days,
            if analysis.short_days == 1 { "" } else { "s" },
            if analysis.short_days == 1 {
                "is"
            } else {
                "are"
            }
        );
    }
    html.push_str(
        "</p><p class=\"note\">Change the bases with --heating-base and --cooling-base: the \
         right heating base is the outside temperature at which this house stops needing heat, \
         which is lower the better it is insulated and the cooler it is kept.</p></section>",
    );
    html
}

/// A temperature in a table column: always one decimal, so the column lines up.
fn table_celsius(celsius: Option<f64>) -> String {
    match celsius {
        Some(celsius) if celsius.is_finite() => {
            let text = format!("{celsius:.1}");
            let text = if text == "-0.0" { "0.0" } else { &text };
            format!("{text} °C")
        }
        _ => "-".to_string(),
    }
}

/// Degree days in a table column: always one decimal, grouped from a thousand.
fn table_degree_days(value: f64) -> String {
    if !value.is_finite() {
        return "-".to_string();
    }
    let text = format!("{:.1}", value.abs());
    let (whole, fraction) = text.split_once('.').unwrap_or((&text, "0"));
    let mut grouped = String::with_capacity(whole.len() + whole.len() / 3);
    for (index, digit) in whole.chars().enumerate() {
        if index > 0 && (whole.len() - index) % 3 == 0 {
            grouped.push(',');
        }
        grouped.push(digit);
    }
    let sign = if value < 0.0 && text != "0.0" {
        "-"
    } else {
        ""
    };
    format!("{sign}{grouped}.{fraction}")
}

/// `12 °C`, `-3.5 °C`.
pub fn format_celsius(celsius: f64) -> String {
    let text = format!("{celsius:.1}");
    let text = text.strip_suffix(".0").unwrap_or(&text);
    // A rounded -0.04 would otherwise read as "-0".
    let text = if text == "-0" { "0" } else { text };
    format!("{text} °C")
}

fn format_optional_celsius(celsius: Option<f64>) -> String {
    celsius.map_or_else(|| "-".to_string(), format_celsius)
}

/// Degree days as a table states them: `412`, `3,021`, `3.5`.
pub fn format_degree_days(value: f64) -> String {
    if !value.is_finite() {
        return "-".to_string();
    }
    if value == 0.0 {
        return "0".to_string();
    }
    if value.abs() < 10.0 {
        let text = format!("{value:.1}");
        return text.strip_suffix(".0").unwrap_or(&text).to_string();
    }
    let digits = format!("{:.0}", value.abs());
    let mut grouped = String::with_capacity(digits.len() + digits.len() / 3);
    for (index, digit) in digits.chars().enumerate() {
        if index > 0 && (digits.len() - index) % 3 == 0 {
            grouped.push(',');
        }
        grouped.push(digit);
    }
    if value < 0.0 {
        format!("-{grouped}")
    } else {
        grouped
    }
}

fn stylesheet() -> String {
    // The diverging pair: heating demand cold blue, cooling demand warm red, each stepped
    // for its own surface and validated together for colour vision deficiency.
    let mut css = theme_stylesheet(
        "  --hdd: #2a78d6;\n  --cdd: #e34948;\n",
        "  --hdd: #3987e5;\n  --cdd: #e66767;\n",
    );
    css.push_str(CHROME_CSS);
    css.push_str(DEGREE_CSS);
    css
}

